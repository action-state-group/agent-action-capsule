#!/usr/bin/env python3
"""Regenerate the reproducible vector corpora and their checksums."""
from __future__ import annotations

import hashlib
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VECTORS = ROOT / "vectors"


def checksums(directory: Path) -> None:
    lines = []
    # Sort by the relative path string, as the committed files are, not by
    # Path, which compares component by component.
    files = sorted(
        (p.relative_to(directory).as_posix(), p) for p in directory.rglob("*") if p.is_file()
    )
    for relative, path in files:
        if path.name == "SHA256SUMS" or "__pycache__" in path.parts or path.suffix == ".pyc":
            continue
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        lines.append(f"{digest}  {relative}")
    (directory / "SHA256SUMS").write_text("\n".join(lines) + "\n", encoding="utf-8")


def viewer_core_text() -> None:
    """The viewer core-text corpus: generated by the TypeScript core text
    (ts/src/verification-page.ts), its reference."""
    ts = ROOT / "ts"
    if not (ts / "node_modules").is_dir():
        print(
            "skip viewer-core-text: run `npm ci` in ts/ to regenerate it",
            file=sys.stderr,
        )
        return
    subprocess.run(
        [
            "npx",
            "vitest",
            "run",
            "test/verification-states.test.ts",
        ],
        check=True,
        cwd=ts,
        env={**os.environ, "AAC_WRITE_VECTORS": "1"},
    )


# Run in this order: a base generator rewrites its corpus manifest with only its
# own cases, and the generators after it append theirs, so every manifest keeps
# its released order. A full run must leave vectors/ unchanged; the Vector
# regeneration workflow checks it.
GENERATORS = (
    # vectors/capsule/ (and provenance-mode-vectors/), in manifest order.
    "generate_vectors.py",
    "generate_canonical_differential.py",
    "generate_reference_vectors.py",
    "generate_spec_derived_vectors.py",
    "generate_v05_vectors.py",
    "generate_typed_field_vectors.py",
    "generate_disclosure_vectors.py",
    "generate_producer_envelope_vectors.py",
    "generate_evidence_request_vectors.py",
    "generate_settlement_vectors.py",
    "generate_evidence_layer_padding_vectors.py",
    "generate_cll_material_vectors.py",
    "generate_min_necessary_vectors.py",
    "generate_bundle_producer_key_vectors.py",
    "generate_bundle_composed_vectors.py",
    # Reuses the composed generator's records, keys and block helpers.
    "generate_bundle_composed_cb_vectors.py",
    "generate_bundle_strict_vectors.py",
    # Reuses the strict generator's records, keys and checkpoint signer.
    "generate_bundle_02_vectors.py",
    "generate_bundle_producer_fixture.py",
    "generate_verify_number_findings_fixture.py",
    "generate_judgment_extension_vectors.py",
    "generate_profile_vectors.py",
    "generate_interop_profile_v0_vectors.py",
    "generate_personal_history_basic_v0_vectors.py",
    "generate_coverage_declaration_v0_vectors.py",
    "generate_controller_binding_v0_vectors.py",
    "generate_deal_reconcile_v0_vectors.py",
    "generate_registry_conformance_vectors.py",
    "generate_adapter_x402_vectors.py",
    "generate_ucp_adapter_vectors.py",
    # Reads the x402 adapter corpus, so it runs after it.
    "generate_personal_history_outcome_v0_vectors.py",
    # Append to the capsule, disclosure-envelope and producer-envelope manifests.
    "generate_parity_hardening_vectors.py",
    "generate_envelope_encoding_vectors.py",
    # Appends to the capsule manifest.
    "generate_negative_zero_vectors.py",
)


def main() -> None:
    python = sys.executable
    for script in GENERATORS:
        subprocess.run([python, str(Path(__file__).with_name(script))], check=True, cwd=ROOT / "python")
    viewer_core_text()
    for corpus in (
        VECTORS / "capsule",
        VECTORS / "producer-envelope",
        VECTORS / "disclosure-envelope",
        VECTORS / "interop" / "composition",
        VECTORS / "interop" / "ran_under",
    ):
        checksums(corpus)
    # The top-level list covers every file under vectors/.
    checksums(VECTORS)


if __name__ == "__main__":
    main()
