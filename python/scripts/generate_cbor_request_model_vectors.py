"""Generate the CBOR request data-model vectors in ../../vectors/cbor-request-model/.

A request in the CBOR binding is read only in core deterministic encoding
(RFC 8949 §4.2.1) and only when every item, at every depth and inside members
a responder ignores, is null, false, true, a text string, an unsigned integer
up to 2^53 - 1, an array or a map with text keys (``spec/interop-profile-v1.md``
§5.2, #529). Anything else is ``request_malformed``. Before, Go read such a
request when the value sat in a member it ignores, while Python and Rust
refused it, so one request was answered by one implementation and refused by
two.

Each case is the CBOR encoding of the minimal valid Evidence Request of
``vectors/cbor-nesting/`` whose open-world member ``x`` holds the item under
test; ``accept`` says whether a request reader reads it.

Output: ``cases.json``, ``manifest.json`` and ``SHA256SUMS`` in
``vectors/cbor-request-model/`` (or ``--out DIR``). ``README.md`` is
hand-written; when present it is included in ``SHA256SUMS`` but never
rewritten. Deterministic: no clock, randomness or keys.

Run: cd python && python scripts/generate_cbor_request_model_vectors.py
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_cbor_nesting_vectors import request  # noqa: E402
from vector_layout import dumps  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "vectors" / "cbor-request-model"

# (id, description, CBOR of member x in hex, accept)
CASES = (
    ("pos-null", "x is null: read.", "f6", True),
    ("pos-max-integer", "x is 2^53 - 1, the largest integer in the data model: read.", "1b001fffffffffffff", True),
    ("pos-containers", 'x is [{"a": true}, "t", 0], every item in the data model: read.', "83a16161f5617400", True),
    ("neg-tag", "x is tag 1000 around null: a tag is outside the data model.", "d903e8f6", False),
    ("neg-tag-nested", 'x is [{"a": 1(0)}]: a tag deep inside an ignored member is refused too.', "81a16161c100", False),
    ("neg-float-half", "x is 1.0 as a half-precision float: no float is in the data model.", "f93c00", False),
    ("neg-float-single", "x is 1.5 as a single-precision float.", "fa3fc00000", False),
    ("neg-float-double", "x is 1.5 as a double-precision float.", "fb3ff8000000000000", False),
    ("neg-negative-integer", "x is -1: integers are unsigned.", "20", False),
    ("neg-integer-above-limit", "x is 2^53: above the largest integer JCS represents exactly.", "1b0020000000000000", False),
    ("neg-byte-string", "x is the byte string h'00': a request holds no byte string.", "4100", False),
    ("neg-integer-map-key", "x is {1: 0}: map keys are text.", "a10100", False),
    ("neg-undefined", "x is undefined: no simple value but false, true and null.", "f7", False),
    ("neg-simple-value", "x is simple(16).", "f0", False),
    ("neg-non-shortest-integer", "x is 0 with a one-byte argument: not the shortest form.", "1800", False),
    ("neg-indefinite-array", "x is an empty indefinite-length array: lengths are definite.", "9fff", False),
    ("neg-indefinite-text", 'x is "a" as an indefinite-length text string.', "7f6161ff", False),
    ("neg-unsorted-keys", 'x is {"b": null, "a": null}: map keys out of deterministic order.', "a26162f66161f6", False),
)


def cases() -> list[dict]:
    return [
        {
            "id": case_id,
            "description": description,
            "accept": accept,
            "cbor_hex": request(bytes.fromhex(member)).hex(),
        }
        for case_id, description, member, accept in CASES
    ]


def write(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    doc = {
        "description": (
            "A request in the CBOR binding is read only in core deterministic encoding with every "
            "item, at every depth and inside ignored members, in the request data model: null, "
            "false, true, text, unsigned integers up to 2^53 - 1, arrays and maps with text keys "
            "(#529). Anything else is request_malformed. Generated by "
            "python/scripts/generate_cbor_request_model_vectors.py."
        ),
        "cases": cases(),
    }
    body = dumps(doc)
    (out / "cases.json").write_text(body, encoding="utf-8")
    manifest = {
        "spec": "spec/interop-profile-v1.md",
        "provenance": "spec-derived",
        "generator": "python/scripts/generate_cbor_request_model_vectors.py",
        "files": [{
            "path": "cases.json",
            "sha256": hashlib.sha256(body.encode("utf-8")).hexdigest(),
            "count": len(doc["cases"]),
        }],
    }
    (out / "manifest.json").write_text(dumps(manifest), encoding="utf-8")
    lines = [f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.name}"
             for p in sorted(out.iterdir()) if p.is_file() and p.name != "SHA256SUMS"]
    (out / "SHA256SUMS").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=OUT)
    write(parser.parse_args().out)


if __name__ == "__main__":
    main()
