def render() -> dict[str, str]:
    """Return {relative path: file text} for every generated file."""
    files: dict[str, str] = {}
    manifest = []
    for case in cases():
        record, labels = case["built"]
        got = check_record(record)
        if got != case["expect"]:
            raise AssertionError(f"{case['file']}: rules {got} != expected {case['expect']}")
        doc = {
            "_status": STATUS,
            "_note": case["note"],
            "expect": {"valid": not case["expect"], "violations": case["expect"]},
            "digest_labels": labels,
            "record": record,
        }
        files[case["file"]] = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
        manifest.append(
            {"file": case["file"], "valid": not case["expect"], "violations": case["expect"]}
        )
    files["manifest.json"] = (
        json.dumps(
            {
                "generator": "python/scripts/generate_profile_vectors.py",
                "label_digest": 'json_digest({"label": <label>})',
                "rules": list(RULES),
                "cases": manifest,
            },
            indent=2,
        )
        + "\n"
    )
    return files


def main() -> None:
    for rel, text in render().items():
        path = OUT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
