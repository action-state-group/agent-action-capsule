def _event_id_as_digest(
    base: tuple[dict[str, Any], list[dict[str, str]]],
) -> tuple[dict[str, Any], list[dict[str, str]]]:
    record, labels = copy.deepcopy(base)
    record["subject"]["semantic_digest"] = record["subject"]["event_id"]
    event_label = next(x["label"] for x in labels if x["path"] == "subject.event_id")
    for x in labels:
        if x["path"] == "subject.semantic_digest":
            x["label"] = event_label
    return record, labels


def _with_judgment_field(
    base: tuple[dict[str, Any], list[dict[str, str]]], key: str, value: Any
) -> tuple[dict[str, Any], list[dict[str, str]]]:
    record, labels = copy.deepcopy(base)
    record["judgment"][key] = value
    return record, labels


