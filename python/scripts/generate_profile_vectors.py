"""Generate the Buzz profile vectors in ../../vectors/profiles/.

Illustrative EvidenceRecord fixtures for the ``nostr-pubkey`` host-principal profile and the
three Buzz Evidence Contract profiles (``buzz.agent-job/v1``, ``buzz.moderation/v1``,
``buzz.release/v1``). Every record carries the one uniform subject shape
``subject: {event_id, semantic_digest}``; any further digested fact is a NAMED body digest in
``payload_commitments`` (``role`` names the fact), never a second subject field.

Every 64-hex value is ``json_digest({"label": <label>})`` over a labelled placeholder, and each
fixture lists its ``digest_labels`` so the Go and TypeScript parity tests re-derive every value
from the same label and assert the same committed files. Each fixture also carries ``expect``:
the rule codes :func:`check_record` must report (empty for a positive).

The rule set is deliberately small and identical in all three languages:

- ``subject_shape``          subject is exactly ``{event_id, semantic_digest}``, both 64-hex.
- ``event_id_as_digest``     the transport event id is reused as a digest (subject or body).
- ``body_digest_named``      every body digest names its fact; none reuses ``semantic_digest``.
- ``message_text_present``   a field whose name marks free text (text/message/content/body).
- ``score_present``          a field whose name marks a score/rating/rank.

Run: cd python && python -m scripts.generate_profile_vectors
"""
from __future__ import annotations

import copy
import json
import re
from pathlib import Path
from typing import Any

from agent_action_capsule.canonical import json_digest

OUT = Path(__file__).resolve().parents[2] / "vectors" / "profiles"

LABEL_PREFIX = "buzz-profile-vector"
HEX64 = re.compile(r"^[0-9a-f]{64}$")
TEXT_KEY = re.compile(r"(^|_)(text|message|content|body)(_|$)")
SCORE_KEY = re.compile(r"(^|_)(score|rating|rank)(_|$)")
RULES = (
    "subject_shape",
    "event_id_as_digest",
    "body_digest_named",
    "message_text_present",
    "score_present",
)

STATUS = (
    "Subject shape ruled 2026-09-23 (uniform `semantic_digest`). Illustrative vector generated by "
    "python/scripts/generate_profile_vectors.py; registry placement is still unruled. See "
    "vectors/profiles/README.md."
)


def label(kind: str, item: str) -> str:
    return f"{LABEL_PREFIX}:{kind}:{item}"


def digest(lbl: str) -> str:
    return json_digest({"label": lbl})


# ---------------------------------------------------------------------------------------------
# Rule checker (mirrored in go/canonical/profile_vectors_test.go and ts/test/profile-vectors.test.ts)


def _walk_keys(value: Any, path: str = "") -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    if isinstance(value, dict):
        for key in sorted(value):
            child = f"{path}.{key}" if path else key
            out.append((key, child))
            out.extend(_walk_keys(value[key], child))
    elif isinstance(value, list):
        for i, item in enumerate(value):
            out.extend(_walk_keys(item, f"{path}.{i}"))
    return out


def check_record(record: dict[str, Any], disabled: frozenset[str] = frozenset()) -> list[str]:
    """Return the sorted rule codes ``record`` violates, skipping any rule in ``disabled``."""
    found: set[str] = set()
    subject = record.get("subject")
    event_id = None
    if not (
        isinstance(subject, dict)
        and set(subject) == {"event_id", "semantic_digest"}
        and all(isinstance(subject[k], str) and HEX64.match(subject[k]) for k in subject)
    ):
        found.add("subject_shape")
    else:
        event_id = subject["event_id"]
    commitments = record.get("payload_commitments", [])
    body_digests = [c.get("digest") for c in commitments if isinstance(c, dict)]
    if event_id is not None and (
        subject["semantic_digest"] == event_id or event_id in body_digests
    ):
        found.add("event_id_as_digest")
    for c in commitments:
        role = c.get("role") if isinstance(c, dict) else None
        if not isinstance(role, str) or not role or role == "semantic_digest":
            found.add("body_digest_named")
    for key, _ in _walk_keys(record):
        if TEXT_KEY.search(key):
            found.add("message_text_present")
        if SCORE_KEY.search(key):
            found.add("score_present")
    return sorted(found - disabled)


