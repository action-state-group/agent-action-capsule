const preCitationPurpose = "## 1. `verdict_class`\n\n| Value | Semantics |\n|---|---|\n| `executed` | ran |\n\n" +
	"## 2. `disposition.decision`\nInitial contents: `accept`, `reject`.\n\n" +
	"## 3. `effect.type`\nInitial contents: `write_order`.\n\n" +
	"## 4. `irreversibility_class`\n\n1. `two_way`\n\n" +
	"## 5. `effect_attestation`\n\n| Value | Semantics |\n|---|---|\n| `gate_executed` | observed |\n\n" +
	"## 6. `chain.relation`\n\n| Value | Semantics |\n|---|---|\n| `confirms` | non-terminal |\n\n## No registry\n"

// Regression: an older snapshot that predates citation_purpose used to load it
// as an empty set; it is now absent, so callers can tell the two apart.
func TestOlderSnapshotOmitsCitationPurpose(t *testing.T) {
	path := filepath.Join(t.TempDir(), "REGISTRY.md")
	require.NoError(t, os.WriteFile(path, []byte(preCitationPurpose), 0o644))
	known, err := Load(path)
	require.NoError(t, err)
	_, has := known["citation_purpose"]
	assert.False(t, has)
	_, has = known["epistemic_type"]
	assert.False(t, has)
	assert.True(t, known["chain.relation"]["confirms"])
}

func TestOlderSnapshotRequiresCoreRegistries(t *testing.T) {
	path := filepath.Join(t.TempDir(), "REGISTRY.md")
	broken := strings.Replace(preCitationPurpose, "1. `two_way`", "Prose only.", 1)
	require.NoError(t, os.WriteFile(path, []byte(broken), 0o644))
	_, err := Load(path)
	assert.ErrorContains(t, err, "irreversibility_class")
}

func TestEmptyNonCoreRegistryIsEmptyNotAbsent(t *testing.T) {
	tables, err := ParseTables(strings.NewReader("## 14. Evidence Bundle extension kind\n\nNo initial extension kind is defined.\n"))
	require.NoError(t, err)
	require.Len(t, tables, 1)
	assert.Equal(t, "evidence_bundle.extension_kind", tables[0].Name)
	assert.Empty(t, tables[0].Values)
}
