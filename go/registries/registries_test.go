// registriesDoc is the shape of registries.json.
type registriesDoc struct {
	Source      string           `json:"source"`
	GeneratedBy string           `json:"generated_by"`
	Registries  map[string]Table `json:"registries"`
}

func TestEmbeddedJSONMatchesGoParse(t *testing.T) {
	// Parity: registries.json is generated by the Python parser; the Go parser
	// must read the same embedded REGISTRY.md to the same tables.
	var doc registriesDoc
	require.NoError(t, json.Unmarshal(registriesJSON, &doc))
	tables, err := ParseTables(bytes.NewReader(authoritativeRegistry))
	require.NoError(t, err)
	require.Len(t, doc.Registries, len(tables))
	for _, tbl := range tables {
		want, ok := doc.Registries[tbl.Name]
		require.True(t, ok, tbl.Name)
		want.Name = tbl.Name
		assert.Equal(t, want, tbl, tbl.Name)
	}
	// Document order is preserved in the JSON object.
	dec := json.NewDecoder(bytes.NewReader(registriesJSON))
	var keys []string
	depth := 0
	for {
		tok, err := dec.Token()
		if err != nil {
			break
		}
		switch v := tok.(type) {
		case json.Delim:
			if v == '{' || v == '[' {
				depth++
			} else {
				depth--
			}
		case string:
			if depth == 2 && dec.More() {
				keys = append(keys, v)
				var skip json.RawMessage
				require.NoError(t, dec.Decode(&skip))
			}
		}
	}
	assert.Equal(t, AllRegistryNames, keys)
}

